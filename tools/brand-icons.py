#!/usr/bin/env python3
"""Writes wwwroot/js/brands.js: the badge (brand mark + tile colours) of every program AI Tweaker installs or configures.

Marks come from Simple Icons (simpleicons.org, CC0); the trademarks belong to their owners and are only used to show
which program a row is about. Programs without a published mark get a line glyph from icons.js on the same tile.

Usage:  npm pack simple-icons && tar -xzf simple-icons-*.tgz
        python3 tools/brand-icons.py path/to/package
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "AITweaker.App", "wwwroot", "js", "brands.js")

# program / guide id -> (Simple Icons slug or "icon:<line glyph>", tile gradient top, bottom, glyph colour)
BADGES = {
    "chrome": ("googlechrome", "#5b9cf8", "#1f63d6", "#fff"),
    "discord": ("discord", "#7983f5", "#4752c4", "#fff"),
    "telegram": ("telegram", "#45b8ea", "#1d8fc4", "#fff"),
    "ayugram": ("icon:send", "#a07bff", "#6a3fd6", "#fff"),
    "steam": ("steam", "#2f5677", "#121821", "#fff"),
    "epic": ("epicgames", "#4a4a4a", "#141414", "#fff"),
    "ea": ("ea", "#ff6a4d", "#d42a2a", "#fff"),
    "spotify": ("spotify", "#2be06d", "#14a64a", "#000"),
    "obs": ("obsstudio", "#4b4a50", "#1b1a1d", "#fff"),
    "mpv": ("mpv", "#9a4a9a", "#4e1450", "#fff"),
    "lightshot": ("icon:feather", "#b57cf0", "#7a3fc6", "#fff"),
    "7zip": ("7zip", "#4a4a4a", "#151515", "#fff"),
    "vcredist": ("icon:box", "#4a9be0", "#1d5fa8", "#fff"),
    "directx": ("icon:cube", "#4a9be0", "#1d5fa8", "#fff"),
    "dotnet8": ("dotnet", "#7a52e8", "#46219e", "#fff"),
    "openshell": ("icon:start", "#59a0d6", "#26609a", "#fff"),
    "cru": ("icon:monitor", "#5f6b7d", "#2d3644", "#fff"),
    "nvidia-app": ("nvidia", "#86c90f", "#4d7a00", "#fff"),
    "amd-software": ("amd", "#f2353c", "#a50f15", "#fff"),
    # Chrome extensions
    "ublock-lite": ("ublockorigin", "#9c1c1c", "#5e0d0d", "#fff"),
    "sponsorblock": ("icon:skip", "#1b9c4e", "#0d6a33", "#fff"),
    "deepl": ("deepl", "#1b3a6b", "#0f2244", "#fff"),
    "volume-master": ("icon:volume", "#3f74d6", "#22489a", "#fff"),
}


def main():
    pkg = sys.argv[1] if len(sys.argv) > 1 else "package"
    data = json.load(open(os.path.join(pkg, "data", "simple-icons.json"), encoding="utf-8"))
    version = json.load(open(os.path.join(pkg, "package.json"), encoding="utf-8"))["version"]
    icons = data if isinstance(data, list) else data.get("icons", data)
    titles = {i.get("slug") or re.sub(r"[^a-z0-9]", "", i["title"].lower()): i["title"] for i in icons}
    rows = []
    for pid, (src, top, bottom, ink) in BADGES.items():
        if src.startswith("icon:"):
            mark = f'"{src}"'
        else:
            svg = open(os.path.join(pkg, "icons", f"{src}.svg"), encoding="utf-8").read()
            mark = json.dumps(re.search(r' d="([^"]+)"', svg).group(1))
            assert src in titles, src
        rows.append(f'    {json.dumps(pid)}: [{mark}, "{top}", "{bottom}", "{ink}"],')
    body = "\n".join(rows)
    js = f"""/* Program badges: brand marks from Simple Icons {version} (CC0, simpleicons.org) — the trademarks belong to their owners.
   Programs without a published mark use a line glyph from icons.js. Generated by tools/brand-icons.py; don't edit by hand. */
(function () {{
  const B = {{
{body}
  }};

  /** Badge for a program or guide id; unknown ids get the first two letters of the name on the accent colour. */
  window.brandIcon = (id, name = "", cls = "") => {{
    const b = B[id];
    if (!b) return `<span class="app-ico mono ${{cls}}">${{esc(String(name).slice(0, 2).toUpperCase())}}</span>`;
    const [mark, top, bottom, ink] = b;
    const glyph = mark.startsWith("icon:") ? icon(mark.slice(5)) : `<svg viewBox="0 0 24 24" aria-hidden="true"><path d="${{mark}}"/></svg>`;
    return `<span class="app-ico ${{cls}}" style="--ai-t:${{top}};--ai-b:${{bottom}};--ai-i:${{ink}}">${{glyph}}</span>`;
  }};
}})();
"""
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print(f"{OUT}: {len(BADGES)} badges")


if __name__ == "__main__":
    main()
