#!/usr/bin/env python3
"""Regenerates wwwroot/js/mock-data.js from the real catalog so the UI demo mode
(opened in a normal browser, outside WebView2) shows the actual tweaks, guides, apps and BIOS items.

Usage: python3 tools/gen-mock-data.py
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "src", "AITweaker.Core", "Data")
OUT = os.path.join(ROOT, "src", "AITweaker.App", "wwwroot", "js", "mock-data.js")


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return json.load(f)


def describe(a):
    t = a["type"]
    if t == "registry":
        if a.get("delete"):
            return f"reg delete {a['path']} /v {a.get('name', '')}"
        return f"reg set {a['path']} \\ {a.get('name') or '(default)'} = {a.get('value')} ({a.get('kind', 'dword')})"
    if t == "service":
        return f"service {a['name']} -> {a.get('startup', 'disabled')}"
    if t == "task":
        return f"task {a['path']} -> disabled"
    if t == "powercfg":
        return f"powercfg {a.get('alias', a['setting'])} AC={a.get('ac', '-')} DC={a.get('dc', '-')}"
    if t == "powerScheme":
        return f"power scheme -> {a.get('scheme', 'high')}" + (f" (overlay {a['overlay']})" if a.get("overlay") else "")
    if t == "bcd":
        return f"bcdedit /set {a['element']} {a['value']}" if a.get("value") else f"bcdedit /deletevalue {a['element']}"
    if t == "command":
        return f"{a['file']} {a.get('args', '')}"
    if t == "powershell":
        return "powershell: " + a["script"]
    if t == "device":
        return "device " + ", ".join(a["match"]) + " -> disabled"
    if t == "nic":
        return f"nic[{a.get('target', 'all')}] " + ", ".join(f"{k}={v}" for k, v in a["keywords"].items())
    if t == "msi":
        return f"MSI mode -> {a['target']}"
    if t == "affinity":
        return "interrupt affinity -> " + ", ".join(a.get("targets", ["gpu", "nic", "usb"]))
    if t == "directx":
        return f"DirectX {a['key']}={a['value']}"
    if t == "appx":
        return "remove appx " + ", ".join(a["packages"])
    if t == "display":
        return "display -> max refresh rate"
    if t == "wallpaper":
        return f"wallpaper[{a.get('target', 'desktop')}] -> AI Tweaker {a.get('variant', 'dark')}"
    return t


# Mirror of OfflineImagePlan.Reject (C#) for the demo preview of the AI Tweaker image.
IMAGE_FACTS = {"os.build", "os.win11"}
OFFLINE_ROOTS = ("HKLM\\SOFTWARE\\", "HKLM\\SYSTEM\\CURRENTCONTROLSET\\", "HKCU\\")


def decidable(when):
    if not when:
        return True
    ids = set(re.findall(r"[A-Za-z_][A-Za-z0-9_.]*", re.sub(r'"[^"]*"', "", when))) - {"true", "false"}
    return ids <= IMAGE_FACTS


def offline(t):
    if not decidable(t.get("when")):
        return False
    for a in t["actions"]:
        if not decidable(a.get("when")):
            return False
        if a["type"] == "registry":
            if "*" in a["path"] or not a["path"].upper().startswith(OFFLINE_ROOTS):
                return False
        elif a["type"] not in ("service", "wallpaper"):
            return False
    return True


tweaks = []
for path in sorted(glob.glob(os.path.join(DATA, "tweaks", "*.json"))):
    with open(path, encoding="utf-8") as f:
        for t in json.load(f):
            tweaks.append({
                "id": t["id"], "category": t["category"], "name": t["name"], "description": t["description"],
                "level": t.get("level", 2), "risk": t.get("risk", "low"), "confirm": t.get("confirm", False),
                "confirmText": t.get("confirmText"), "reboot": t.get("reboot", False), "logoff": t.get("logoff", False),
                "restartExplorer": t.get("restartExplorer", False), "reversible": t.get("reversible", True),
                "when": t.get("when"), "why": t.get("why"), "actions": [describe(a) for a in t["actions"]], "offline": offline(t),
            })

data = {
    "categories": load("categories.json"),
    "tweaks": tweaks,
    "apps": load("apps.json"),
    "guides": load("guides.json"),
    "bios": load("bios.json"),
}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/gen-mock-data.py from src/AITweaker.Core/Data — do not edit. Used only by the browser demo mode. */\n")
    f.write("window.MOCK_DATA = ")
    json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(f"wrote {OUT}: {len(tweaks)} tweaks")
